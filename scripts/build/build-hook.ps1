# Builds the hook DLLs with the installed MSVC toolchain (ADR-0002):
#   build\hook\VERSION.dll    proxy that forwards to System32\version.dll and loads atlasre.dll (src\hook\proxy)
#   build\hook\atlasre.dll    hook runtime + reimplementations (src\hook, src\reimpl, src\third_party\minhook)
#   build\hook\manifest.json  commit, dirty flag, toolset, compiled-in IDs, SHA-256 of the outputs
# Every build embeds the commit and dirty flag (the DLLs' sources only); atlasre.dll logs them at start-up.
# Then runs tests\hook\proxy_test.c against the fresh DLLs (skip with -NoTest).
# Usage: powershell -ExecutionPolicy Bypass -File D:\ATLAS\_tools\build-hook.ps1 [-NoTest]
param([switch]$NoTest)
$ErrorActionPreference = 'Stop'
$repo = Split-Path $PSScriptRoot
$src = Join-Path $repo 'src'
$out = Join-Path $repo 'build\hook'
$obj = Join-Path $out 'obj'
$gen = Join-Path $out 'gen'
foreach ($d in $out, $obj, $gen) { New-Item -ItemType Directory -Force $d | Out-Null }
Get-ChildItem $obj -File | Remove-Item

# Import the x64 developer environment into this session (a .cmd file avoids cmd /c quoting problems).
$vswhere = "${env:ProgramFiles(x86)}\Microsoft Visual Studio\Installer\vswhere.exe"
$vs = & $vswhere -latest -products * -requires Microsoft.VisualStudio.Component.VC.Tools.x86.x64 -property installationPath
$envCmd = Join-Path $obj 'env.cmd'
$installer = Split-Path $vswhere  # vcvars64.bat calls vswhere.exe itself and expects it on PATH
Set-Content -Path $envCmd -Encoding ascii -Value "@set `"PATH=$installer;%PATH%`"`r`n@call `"$vs\VC\Auxiliary\Build\vcvars64.bat`" >nul`r`n@set"
foreach ($line in (cmd /c $envCmd)) {
    if ($line -match '^([^=]+)=(.*)$') { Set-Item -Path "env:$($matches[1])" -Value $matches[2] }
}
if (-not (Get-Command cl.exe -ErrorAction SilentlyContinue)) { throw "vcvars64.bat did not put cl.exe on PATH ($vs)" }
$toolset = "MSVC $env:VCToolsVersion"

function Invoke-Tool([string]$exe, [string[]]$arguments) {
    & $exe @arguments
    if ($LASTEXITCODE -ne 0) { throw "$exe failed with exit code $LASTEXITCODE" }
}

# Build provenance header.
$commit = (git -C $repo rev-parse --short=12 HEAD).Trim()
# Dirty = uncommitted changes in the DLLs' own inputs (other work under src\, e.g. the launcher, does not count).
$dirty = [bool](git -C $repo status --porcelain -- src/hook src/reimpl src/sdk src/third_party/minhook)
$built = Get-Date -Format 'yyyy-MM-dd HH:mm:ss'
Set-Content -Path (Join-Path $gen 'atlasre_build.h') -Encoding ascii -Value @(
    '// Generated by _tools/build-hook.ps1; do not edit.',
    '#pragma once',
    "#define ATLASRE_COMMIT `"$commit`"",
    "#define ATLASRE_DIRTY $([int]$dirty)",
    "#define ATLASRE_BUILT `"$built`"",
    "#define ATLASRE_COMPILER `"$toolset`""
)

$common = @('/nologo', '/c', '/O2', '/MT', '/GS', '/Zi', '/utf-8', '/DWIN32_LEAN_AND_MEAN', '/DNOMINMAX',
            '/D_CRT_SECURE_NO_WARNINGS', "/Fd$obj\vc.pdb", "/Fo$obj\")
$minhook = Join-Path $src 'third_party\minhook'

Write-Host "== MinHook ($toolset)"
Invoke-Tool cl.exe ($common + @('/W3', '/TC', "/I$minhook\include",
    "$minhook\src\buffer.c", "$minhook\src\hook.c", "$minhook\src\trampoline.c", "$minhook\src\hde\hde64.c"))

Write-Host '== atlasre'
$cpp = @(Get-ChildItem "$src\hook" -Filter *.cpp -File) + @(Get-ChildItem "$src\reimpl" -Filter *.cpp -File -Recurse)
Invoke-Tool cl.exe ($common + @('/W4', '/std:c++20', '/EHsc', '/permissive-', "/I$src\hook", "/I$src\sdk", "/I$gen",
    "/I$minhook\include") + ($cpp | ForEach-Object { $_.FullName }))
$atlasObjs = @('buffer', 'hook', 'trampoline', 'hde64') + ($cpp | ForEach-Object { $_.BaseName }) |
    ForEach-Object { Join-Path $obj "$_.obj" }
Invoke-Tool link.exe (@('/nologo', '/DLL', '/DEBUG', '/OPT:REF', '/OPT:ICF', "/OUT:$out\atlasre.dll",
    "/PDB:$out\atlasre.pdb", "/IMPLIB:$obj\atlasre.lib") + $atlasObjs + @('kernel32.lib'))

Write-Host '== VERSION.dll proxy (server)'
Invoke-Tool cl.exe ($common + @('/W4', '/TC', "$src\hook\proxy\version_proxy.c"))
Invoke-Tool link.exe @('/nologo', '/DLL', '/DEBUG', '/OPT:REF', "/OUT:$out\VERSION.dll", "/PDB:$out\VERSION.pdb",
    "/IMPLIB:$obj\VERSION.lib", "$obj\version_proxy.obj", 'kernel32.lib')

Write-Host '== XINPUT1_3.dll proxy (client)'
Invoke-Tool cl.exe ($common + @('/W4', '/TC', "$src\hook\proxy\xinput_proxy.c"))
Invoke-Tool link.exe @('/nologo', '/DLL', '/DEBUG', '/OPT:REF', "/OUT:$out\XINPUT1_3.dll", "/PDB:$out\XINPUT1_3.pdb",
    "/IMPLIB:$obj\XINPUT1_3.lib", "$obj\xinput_proxy.obj", 'kernel32.lib')

# Manifest: compiled-in IDs come from the ATLAS_REPLACE lines (same rule as ledger_check.py).
$ids = foreach ($f in $cpp) {
    foreach ($m in [regex]::Matches((Get-Content $f.FullName -Raw), '(?m)^\s*ATLAS_REPLACE\(\s*(SRV|CLI|EDT)\s*,\s*0x([0-9a-fA-F]+)')) {
        "$($m.Groups[1].Value)@$($m.Groups[2].Value.ToLower())"
    }
}
$outputs = [ordered]@{}
foreach ($name in 'VERSION.dll', 'atlasre.dll') {
    $outputs[$name] = (Get-FileHash (Join-Path $out $name) -Algorithm SHA256).Hash.ToLower()
}
[ordered]@{
    commit   = $commit
    dirty    = $dirty
    built    = $built
    toolset  = $toolset
    ids      = @($ids | Sort-Object)
    outputs  = $outputs
} | ConvertTo-Json | Set-Content -Path (Join-Path $out 'manifest.json') -Encoding utf8
Write-Host "Built $out (commit $commit$(if ($dirty) { ', dirty' }), $(@($ids).Count) replacement(s))"

if ($NoTest) { return }
Write-Host '== proxy test'
$test = Join-Path $out 'test'
New-Item -ItemType Directory -Force $test | Out-Null
Get-ChildItem $test -File | Remove-Item
Invoke-Tool cl.exe @('/nologo', '/O2', '/MT', '/W4', '/utf-8', '/D_CRT_SECURE_NO_WARNINGS', "/Fo$obj\",
    "/Fe$test\proxy_test.exe", (Join-Path $repo 'tests\hook\proxy_test.c'), '/link', 'psapi.lib')
Copy-Item "$out\VERSION.dll", "$out\atlasre.dll" $test
Invoke-Tool (Join-Path $test 'proxy_test.exe') @()
